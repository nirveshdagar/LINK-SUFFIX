const CITY_TIMEZONE_MAP: ReadonlyMap<string, string> = new Map(
  CITY_TIMEZONE.map((e) => [e.key, e.tz]),
);

export function tzForGeo(geo: Geo): string | undefined {
  const country = (geo.country ?? '').trim();
  const state = (geo.state ?? '').trim();
  const city = (geo.city ?? '').replace(/\s+/g, '').trim();
  if (!country || !state || !city) return undefined;
  const key = `${country}-${state}-${city}`;
  return CITY_TIMEZONE_MAP.get(key);
}